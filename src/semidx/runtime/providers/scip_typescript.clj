;; Fact emission
;; ---------------------------------------------------------------------------

(defn- facts->batches
  "Group normalized facts into one `FactBatch` per operation. Each fact from
  `scip-normalize` carries exactly one evidence record with one operation."
  [facts covered-paths complete?]
  (->> facts
       (group-by #(-> % :evidence first :operation))
       (sort-by key)
       (mapv (fn [[operation op-facts]]
               {:provider_id provider-id
                :provider_version provider-version
                :operation operation
                :freshness "exact"
                :source_identity {}
                :coverage {:paths (vec covered-paths)
                           :fact_kinds ["unit"]
                           :complete complete?}
                :diagnostics []
                :facts (vec op-facts)}))))

(defn- unmapped-summary [unmapped]
  (when (seq unmapped)
    {:code :scip_symbols_unmapped
     :count (count unmapped)
     :by_reason (into (sorted-map) (frequencies (map :reason unmapped)))
     :message (str (count unmapped)
                   " SCIP symbol occurrences were deliberately not turned into facts")}))

(defn facts-from-index
  "Turn an already-read SCIP index into arbitrated shadow facts.

  Test / fixture seam only — production callers use `shadow-facts-for-project`,
  which generates the index with the repo-managed CLI first.

  `opts`:
  - `:project-root` (required) — used to digest the workspace files SCIP covered;
  - `:expected-document-digests` — optional `relative-path` -> `sha256:...` map
    for the stale gate;
  - `:provider-id` / `:provider-version` — evidence provenance overrides."
  [scip-index {:keys [project-root expected-document-digests]
               prov-id :provider-id
               prov-version :provider-version
               :or {prov-id provider-id prov-version provider-version}}]
  (when-not project-root
    (throw (ex-info "facts-from-index requires :project-root to anchor exact facts"
                    {:error_code :missing_project_root})))
  (let [provider-id prov-id
        provider-version prov-version
        documents (:documents scip-index)
        graded (mapv (fn [doc]
                       (assoc doc :freshness
                              (document-freshness project-root (:relative-path doc)
                                                  expected-document-digests)))
                     documents)
        fresh (filterv #(= :fresh (:state (:freshness %))) graded)
        stale (filterv #(not= :fresh (:state (:freshness %))) graded)
        digest-by-path (into {} (map (juxt :relative-path
                                           (comp :content_digest :freshness))
                                     fresh))
        normalized (scip-normalize/normalize-index
                    {:documents fresh}
                    {:language "typescript"
                     :provider-id provider-id
                     :provider-version provider-version
                     :source-identity (fn [relative-path]
                                        {:content_digest (get digest-by-path relative-path)})})
        covered-paths (mapv :relative-path fresh)
        complete? (empty? stale)
        batches (facts->batches (:facts normalized) covered-paths complete?)
        arbitrated (fact-arbitration/arbitrate-batches batches)
        diagnostics (vec (concat (map #(stale-diagnostic (:relative-path %) (:freshness %))
                                      stale)
                                 (when-let [s (unmapped-summary (:unmapped normalized))]
                                   [s])))]
    {:provider_id provider-id
     :provider_version provider-version
     :result "ready"
     :facts (:facts arbitrated)
     ;; Pre-arbitration facts, one evidence record each, kept so a shadow
     ;; comparison can co-arbitrate the SCIP and legacy fact sets in one pass.
     :raw_facts (vec (:facts normalized))
     :batches (:batches arbitrated)
     :errors (:errors arbitrated)
     :diagnostics diagnostics
     :coverage {:covered_paths covered-paths
                :stale_documents (mapv :relative-path stale)
                :complete complete?}
     :unmapped (:unmapped normalized)}))

(defn shadow-facts-for-project
  "Run the repo-managed `scip-typescript` CLI over `root_path`, then normalize,
  gate, and arbitrate its output into shadow facts.

  Returns a map with `:result` one of:
  - `\"ready\"`   — the CLI ran and produced facts (see `facts-from-index`);
  - `\"unavailable\"` — no CLI resolved; `:reason_codes [\"scip_cli_missing\"]`,
    no facts, and the caller should degrade to tree-sitter / regex;
  - `\"failed\"`  — the CLI resolved but the index run errored; `:diagnostics`
    carries the reason and there are no facts.

  This never throws for a missing or failing toolchain and never writes to a
  snapshot."
  [{:keys [root_path expected_document_digests] :as opts}]
  (when-not root_path
    (throw (ex-info "shadow-facts-for-project requires :root_path"
                    {:error_code :missing_root_path})))
  (let [cli (resolve-cli opts)]
    (if-not cli
      {:provider_id provider-id
       :provider_version provider-version
       :result "unavailable"
       :reason_codes ["scip_cli_missing"]
       :facts []
       :batches []
       :errors []
       :diagnostics [{:code :scip_provider_unavailable
                      :message (str "no scip-typescript CLI resolved for " root_path
                                    "; degrade to tree-sitter/regex")}]
       :coverage {:covered_paths [] :stale_documents [] :complete false}
       :unmapped []}
      (let [{:keys [index error]} (run-scip-index! cli root_path)]
        (if error
          {:provider_id provider-id
           :provider_version provider-version
           :result "failed"
           :cli {:path cli :version (cli-version cli)}
           :facts []
           :batches []
           :errors []
           :diagnostics [error]
           :coverage {:covered_paths [] :stale_documents [] :complete false}
           :unmapped []}
          (-> (facts-from-index index {:project-root root_path
                                       :expected-document-digests expected_document_digests})
              (assoc :cli {:path cli :version (cli-version cli)})))))))
